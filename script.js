document.addEventListener('DOMContentLoaded', () => {

    // --- Language ---
    const i18nEls = document.querySelectorAll('[data-i18n]');
    const metaDesc = document.querySelector('meta[name="description"]');
    const EN = {
        _title: document.title,
        _desc: metaDesc ? metaDesc.content : '',
        _menu_open: 'Open menu',
        _menu_close: 'Close menu',
        _lang: "Türkçe'ye geç"
    };
    i18nEls.forEach(el => { EN[el.dataset.i18n] = el.innerHTML; });

    let currentLang = 'en';
    const langToggleBtn = document.getElementById('langToggle');
    const t = key => (currentLang === 'tr' ? TR : EN)[key];

    function setLanguage(lang, save) {
        currentLang = lang === 'tr' ? 'tr' : 'en';
        const dict = currentLang === 'tr' ? TR : EN;
        i18nEls.forEach(el => {
            const v = dict[el.dataset.i18n];
            if (v !== undefined) el.innerHTML = v;
        });
        document.documentElement.lang = currentLang;
        document.title = t('_title');
        if (metaDesc) metaDesc.content = t('_desc');
        langToggleBtn.textContent = currentLang === 'en' ? 'TR' : 'EN';
        langToggleBtn.setAttribute('aria-label', t('_lang'));
        updateMenuLabel();
        if (save) { try { localStorage.setItem('lang', currentLang); } catch (e) { } }
    }

    langToggleBtn.addEventListener('click', () => {
        setLanguage(currentLang === 'en' ? 'tr' : 'en', true);
    });

    // --- Navbar Scroll Effect ---
    const navbar = document.querySelector('.navbar');
    window.addEventListener('scroll', () => {
        navbar.classList.toggle('scrolled', window.scrollY > 50);
    }, { passive: true });

    // --- Mobile Menu ---
    const hamburger = document.querySelector('.hamburger');
    const navLinks = document.querySelector('.nav-links');

    function updateMenuLabel() {
        const open = hamburger.getAttribute('aria-expanded') === 'true';
        hamburger.setAttribute('aria-label', t(open ? '_menu_close' : '_menu_open'));
    }
    function setMenu(open) {
        navLinks.classList.toggle('active', open);
        hamburger.setAttribute('aria-expanded', String(open));
        document.body.classList.toggle('menu-open', open);
        updateMenuLabel();
    }
    hamburger.addEventListener('click', () => setMenu(!navLinks.classList.contains('active')));
    document.querySelectorAll('.nav-links a').forEach(link => link.addEventListener('click', () => setMenu(false)));
    document.addEventListener('keydown', e => { if (e.key === 'Escape') setMenu(false); });
    window.addEventListener('resize', () => { if (window.innerWidth > 1024) setMenu(false); });

    // --- Smooth Scroll for Internal Links (offset for sticky header) ---
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            const targetId = this.getAttribute('href');
            const targetElement = targetId.length > 1 && document.querySelector(targetId);
            if (!targetElement) return;
            e.preventDefault();
            const offsetPosition = targetElement.getBoundingClientRect().top + window.pageYOffset - navbar.offsetHeight;
            window.scrollTo({ top: offsetPosition, behavior: 'smooth' });
        });
    });

    // --- Scroll Animations ---
    const sections = document.querySelectorAll('.section');
    const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if ('IntersectionObserver' in window && !reduceMotion) {
        const observer = new IntersectionObserver((entries, obs) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('visible');
                    obs.unobserve(entry.target);
                }
            });
        }, { threshold: 0.1 });
        sections.forEach(section => {
            section.classList.add('fade-up');
            observer.observe(section);
        });
    }

    // --- Initial language: ?lang=tr > saved choice > browser language ---
    let initial = new URLSearchParams(location.search).get('lang');
    if (!initial) { try { initial = localStorage.getItem('lang'); } catch (e) { } }
    if (!initial) initial = (navigator.language || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
    setLanguage(initial, false);
});
